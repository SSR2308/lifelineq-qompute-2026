"""Summarize only complete, current-version benchmark/robustness result grids.

Run from the repository root: python scripts/summarize_results.py
This reads measured artifacts. It never trains a circuit or invents a result.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd

from lifelineq.experiments import ExperimentConfig, load_saved, results_rows
from lifelineq.provenance import source_hash, versions


def measured_documents():
    documents = []
    missing = []
    for scenario in ('base', 'demand_shift', 'overlap_shift'):
        for weight in (0., 1., 2.):
            for p in (1, 2):
                for seed in (11, 22, 33, 44, 55):
                    config = ExperimentConfig(scenario_name=scenario, weight=weight, p=p,
                                              seed=seed, shots=2048, starts=2, maxiter=80,
                                              compiler_candidates=4)
                    document = load_saved(config)
                    if document is None:
                        missing.append(str(config))
                    else:
                        documents.append(document)
    if missing:
        raise SystemExit(f'Missing {len(missing)} current-source results; rerun the presets '
                         'before summarizing. First missing configurations:\n'
                         + '\n'.join(missing[:6]))
    return documents


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                      '| ' + ' | '.join('---' for _ in headers) + ' |',
                      *['| ' + ' | '.join(map(str, row)) + ' |' for row in rows]])


def mean_sd(values, scale=1., digits=2):
    return f'{values.mean()*scale:.{digits}f} ± {values.std(ddof=1)*scale:.{digits}f}'


def main():
    documents = measured_documents()
    frame = pd.DataFrame([row for document in documents for row in results_rows(document)])
    frame.to_csv(ROOT/'results'/'verified_runs.csv', index=False)
    keys = ['scenario_name', 'weight', 'p', 'seed', 'noise']
    ordinary = frame[frame.method == 'ordinary']
    searched = frame[frame.method == 'searched']
    pairs = ordinary.merge(searched, on=keys, suffixes=('_ordinary', '_searched'), validate='one_to_one')
    for metric in ['feasible_rate', 'optimal_probability', 'conditional_mean_regret',
                   'two_qubit_gates', 'depth']:
        pairs[metric+'_delta'] = pairs[metric+'_searched'] - pairs[metric+'_ordinary']
    pairs.to_csv(ROOT/'results'/'verified_compiler_pairs.csv', index=False)

    quantum = frame[frame.method != 'uniform_feasible']
    group_keys = ['scenario_name', 'weight', 'p', 'method', 'noise']
    metrics = ['feasible_rate', 'optimal_probability', 'conditional_mean_regret',
               'two_qubit_gates', 'depth', 'simulation_seconds']
    grouped = frame.groupby(group_keys)[metrics].agg(['mean', 'std', 'count'])
    grouped.columns = ['_'.join(column) for column in grouped.columns]
    grouped.to_csv(ROOT/'results'/'verified_summary.csv')
    paired = pairs.groupby(['scenario_name', 'weight', 'p', 'noise'])[
        [m+'_delta' for m in ['feasible_rate', 'optimal_probability', 'conditional_mean_regret',
                             'two_qubit_gates', 'depth']]].agg(['mean', 'std', 'count'])
    paired.columns = ['_'.join(column) for column in paired.columns]
    paired.to_csv(ROOT/'results'/'verified_compiler_summary.csv')

    lines = [
        '# Measured LifelineQ results',
        '',
        'Generated by `python scripts/summarize_results.py` from strict `load_saved` matches. '
        'This report reads actual saved counts; it does not run or modify the quantum experiments. '
        'Files from earlier source hashes or different budgets are excluded.',
        '',
        f'Computational source SHA-256: `{source_hash()}`.',
        '',
        'Tested versions: ' + '; '.join(f'`{key} {value}`' for key, value in versions().items()) + '.',
        '',
        f'Coverage: {len(documents)} complete fits, {len(quantum)} quantum executions and '
        f'{len(frame)-len(quantum)} uniform-feasible executions. Each execution has 2,048 shots. '
        'For each of three predefined scenarios: lambda 0/1/2, p 1/2, seeds 11/22/33/44/55, '
        'two optimizer starts, at most 80 objective evaluations per start, four compiler candidates. '
        'Each fit supplies one ideal execution and six routed executions (two compiler methods × '
        'three noise levels), plus one uniform-feasible classical execution.',
        '',
        'Every “±” below is the sample standard deviation across five fits/evaluation seeds, '
        'not a confidence interval or a pooled-shot error bar. Wilson intervals in individual '
        'JSON/CSV records describe shot uncertainty for that fixed circuit. The same evaluation '
        'seed is reused across arms of a fit; compiler effects are therefore reported as paired '
        'differences across seeds. A positive feasibility/probability delta favors searched; '
        'a negative regret delta favors searched.',
        '',
        '## Base scenario, lambda = 1',
        '',
        'The exact feasible optimum is 36 with six tied allocations. Rates are percentages; '
        'regret uses the fixed lambda=1 utility proxy.',
        '',
    ]
    rows = []
    order = [('uniform_feasible', 'zero'), ('ideal', 'zero'), ('ordinary', 'zero'),
             ('searched', 'zero'), ('ordinary', 'low'), ('searched', 'low'),
             ('ordinary', 'high'), ('searched', 'high')]
    for p in (1, 2):
        for method, noise in order:
            subset = frame[(frame.scenario_name == 'base') & (frame.weight == 1.) &
                           (frame.p == p) & (frame.method == method) & (frame.noise == noise)]
            rows.append([p, method, noise, mean_sd(subset.feasible_rate, 100),
                         mean_sd(subset.optimal_probability, 100),
                         mean_sd(subset.conditional_mean_regret),
                         '—' if method == 'uniform_feasible' else mean_sd(subset.two_qubit_gates, digits=1)])
    lines += [table(['p', 'Method', 'Noise', 'Feasible % ± SD', 'Optimum % ± SD',
                     'Conditional regret ± SD', 'Two-qubit gates ± SD'], rows), '',
              'Uniform feasible has no depth dependence; its two rows repeat the same seeded '
              'baseline. Do not count them as ten independent observations.', '',
              '## Repeat the noise comparison on fixed perturbations', '',
              'Lambda=1 throughout this table. Utility regret is always relative to each '
              'scenario’s own optimum. The two perturbations were specified before evaluation; '
              'their outcomes do not establish robustness to all possible demand changes.', '']
    rows = []
    for scenario in ('demand_shift', 'overlap_shift'):
        for p in (1, 2):
            for method, noise in [('ideal', 'zero'), ('ordinary', 'high'), ('searched', 'high')]:
                subset = frame[(frame.scenario_name == scenario) & (frame.weight == 1.) &
                               (frame.p == p) & (frame.method == method) & (frame.noise == noise)]
                rows.append([scenario, p, method, noise, mean_sd(subset.feasible_rate, 100),
                             mean_sd(subset.optimal_probability, 100),
                             mean_sd(subset.conditional_mean_regret)])
    lines += [table(['Scenario', 'p', 'Method', 'Noise', 'Feasible % ± SD',
                     'Optimum % ± SD', 'Conditional regret ± SD'], rows), '',
              '## Paired compilation effects and predefined perturbations', '',
              'All rows below fix lambda=1. Differences are searched minus ordinary for the '
              'same fit and noise preset, summarized across five seeds. These are descriptive '
              'measurements, not a claim of statistical significance or generalization.', '']
    rows = []
    for scenario in ('base', 'demand_shift', 'overlap_shift'):
        for p in (1, 2):
            for noise in ('low', 'high'):
                subset = pairs[(pairs.scenario_name == scenario) & (pairs.weight == 1.) &
                               (pairs.p == p) & (pairs.noise == noise)]
                rows.append([scenario, p, noise, mean_sd(subset.two_qubit_gates_delta, digits=1),
                             mean_sd(subset.feasible_rate_delta, 100),
                             mean_sd(subset.optimal_probability_delta, 100),
                             mean_sd(subset.conditional_mean_regret_delta)])
    lines += [table(['Scenario', 'p', 'Noise', 'Δ two-qubit gates ± SD',
                     'Δ feasible (pp) ± SD', 'Δ optimum (pp) ± SD',
                     'Δ conditional regret ± SD'], rows), '',
              '## Exact and deterministic greedy allocations', '',
              'Each row is one objective. Ties are retained by the exact solver. The greedy '
              'allocator uses marginal additions followed by improving single swaps.', '']
    rows = []
    for scenario in ('base', 'demand_shift', 'overlap_shift'):
        for weight in (0., 1., 2.):
            d = next(d for d in documents if d['config']['scenario_name'] == scenario
                     and d['config']['weight'] == weight)
            rows.append([scenario, f'{weight:g}', f"{d['exact']['utility']:g}",
                         len(d['exact']['optima']), f"{d['greedy']['utility']:g}",
                         f"{d['exact']['utility']-d['greedy']['utility']:g}"])
    lines += [table(['Scenario', 'Lambda', 'Exact utility', 'Tied optima', 'Greedy utility',
                     'Greedy regret'], rows), '',
              '## Costs and negative outcomes', '']
    compilation = pd.DataFrame([dict(scenario=d['config']['scenario_name'],
        optimization=d['training']['elapsed_seconds'], elapsed=d['elapsed_seconds'],
        search=d['compilation']['search_seconds'], additional=d['compilation']['additional_search_seconds'],
        ordinary=d['compilation']['ordinary']['two_qubit_gates'],
        searched=d['compilation']['searched']['two_qubit_gates'], nfev=d['training']['nfev'],
        selected_success=d['training']['starts'][d['training']['selected_start']]['success'],
        routing_error=max(d['compilation']['noiseless_max_probability_errors'])) for d in documents])
    successes = sum(start['success'] for d in documents for start in d['training']['starts'])
    greedy_misses = [(d['config']['scenario_name'], d['config']['weight']) for d in documents
                     if abs(d['exact']['utility'] - d['greedy']['utility']) > 1e-9]
    rows = []
    for scenario, subset in compilation.groupby('scenario', sort=False):
        rows.append([scenario, len(subset), f'{subset.elapsed.sum():.2f}',
                     f'{subset.optimization.mean():.3f}', f'{subset.search.mean():.3f}',
                     f'{subset.additional.mean():.3f}',
                     f'{(subset.searched < subset.ordinary).sum()}/{len(subset)}',
                     f'{subset.nfev.min()}–{subset.nfev.max()}'])
    lines += [table(['Scenario', 'Fits', 'Sum run time (s)', 'Mean fit time (s)',
                     'Mean total search (s)', 'Mean extra search (s)',
                     'Strict gate reductions', 'Fit evaluations'], rows), '',
        f'- Quantum executions with no feasible shot: **{int(quantum.no_feasible_sample.sum())}/{len(quantum)}**.',
        f'- Quantum executions that observed an exact optimum at least once: '
        f'**{int((quantum.best_feasible_regret == 0).sum())}/{len(quantum)}**. '
        'This does not imply high per-shot optimum probability.',
        f'- COBYLA reported success on **{successes}/{2*len(documents)}** starts; '
        f'**{int(compilation.selected_success.sum())}/{len(documents)}** selected starts reported success. '
        'Budget-limited fits remain in the results; “completed experiment” is not “optimizer converged.”',
        f'- Maximum checked routed noiseless probability discrepancy: **{compilation.routing_error.max():.3g}**.',
        '- Greedy allocation missed the exact optimum in these distinct scenario/lambda cases: '
        + (', '.join(f'`{s}, lambda={w:g}`' for s,w in sorted(set(greedy_misses))) or '**none**') + '.',
        '- Times are measured on the recorded Windows CPU environment, not a performance benchmark '
        'against hardware or an asymptotic speed comparison. Summed run time excludes CLI startup, '
        'reporting and disk writes. Classical exact and greedy timings are preserved in each JSON.',
        '',
        '## One fixed-run shot interval example',
        '',
    ]
    example = next(d for d in documents if d['config']['scenario_name'] == 'base'
                   and d['config']['weight'] == 1 and d['config']['p'] == 1 and d['config']['seed'] == 11)
    rows = []
    for e in example['executions']:
        if e['method'] in ('ordinary', 'searched') and e['noise'] == 'low':
            m = e['metrics']
            rows.append([e['method'], f"{m['feasible_rate']*100:.2f}%",
                f"[{m['feasible_rate_ci'][0]*100:.2f}%, {m['feasible_rate_ci'][1]*100:.2f}%]",
                f"{m['optimal_probability']*100:.2f}%",
                f"[{m['optimal_probability_ci'][0]*100:.2f}%, {m['optimal_probability_ci'][1]*100:.2f}%]",
                f"{m['conditional_mean_utility_se']:.3f}"])
    lines += ['Base scenario, lambda=1, p=1, seed=11, low noise, 2,048 shots. These Wilson '
              'intervals and conditional utility standard errors do not include optimizer-seed '
              'variation or uncertainty in the synthetic scores.', '',
              table(['Method', 'Feasible', '95% Wilson', 'Optimum', '95% Wilson',
                     'Conditional utility SE'], rows), '',
              '## Reproduce and inspect', '',
              '```bash\npython -m lifelineq.experiments --preset benchmark\n'
              'python -m lifelineq.experiments --preset robustness\n'
              'python scripts/summarize_results.py\n```', '',
              '`verified_runs.csv` contains all validated execution rows; '
              '`verified_summary.csv` groups each scenario/lambda/p/method/noise cell. '
              '`verified_compiler_pairs.csv` preserves every paired difference; '
              '`verified_compiler_summary.csv` summarizes five pairs per cell. '
              'Raw JSON retains all counts, fits and compiler candidates. The source hash, '
              'scenario, configuration and dependency versions are checked before inclusion.', '']
    (ROOT/'results'/'REPORT.md').write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote results/REPORT.md and four verified CSV files from {len(documents)} fits.')


if __name__ == '__main__':
    main()
